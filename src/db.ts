import { Pool, type PoolClient, type QueryResultRow } from 'pg'
import SQLite from 'better-sqlite3'

export interface QueryResult<T> {
  rows: T[]
  rowCount: number
}

export interface DB {
  query<T extends QueryResultRow = QueryResultRow>(sql: string, values?: unknown[]): Promise<QueryResult<T>>
  transaction<T>(callback: (db: DB) => Promise<T>): Promise<T>
  close(): Promise<void>
}

const SCHEMA = `
CREATE TABLE IF NOT EXISTS usuarios (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        TEXT NOT NULL,
  email       TEXT NOT NULL UNIQUE,
  senha_hash  TEXT NOT NULL,
  perfil      TEXT NOT NULL CHECK (perfil IN ('produtor_rural','organizador_eventos')),
  telegram_chat_id TEXT UNIQUE,
  criado_em   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS telegram_chat_id TEXT UNIQUE;

CREATE TABLE IF NOT EXISTS telegram_vinculos (
  codigo       TEXT PRIMARY KEY,
  usuario_id   INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  expira_em    BIGINT NOT NULL
);
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'telegram_vinculos'
      AND column_name = 'expira_em'
      AND data_type IN ('timestamp with time zone', 'timestamp without time zone')
  ) THEN
    ALTER TABLE telegram_vinculos
      ALTER COLUMN expira_em TYPE BIGINT
      USING (EXTRACT(EPOCH FROM (expira_em AT TIME ZONE 'UTC')) * 1000)::BIGINT;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS cidades (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       TEXT NOT NULL,
  estado     TEXT,
  pais       TEXT NOT NULL DEFAULT 'Brasil',
  latitude   DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude  DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  UNIQUE (latitude, longitude)
);

CREATE TABLE IF NOT EXISTS preferencias (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id               INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  cidade_id                INTEGER NOT NULL REFERENCES cidades(id),
  horario_envio            VARCHAR(5) NOT NULL DEFAULT '06:00',
  receber_previsao_diaria  BOOLEAN NOT NULL DEFAULT TRUE,
  alerta_chuva_forte       BOOLEAN NOT NULL DEFAULT TRUE,
  alerta_geada             BOOLEAN NOT NULL DEFAULT TRUE,
  limiar_chuva_mm          DOUBLE PRECISION NOT NULL DEFAULT 25,
  limiar_geada_c           DOUBLE PRECISION NOT NULL DEFAULT 3,
  principal                BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE (usuario_id, cidade_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_pref_principal
  ON preferencias (usuario_id) WHERE principal = TRUE;

CREATE TABLE IF NOT EXISTS alertas_enviados (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  cidade_id   INTEGER NOT NULL REFERENCES cidades(id),
  tipo        TEXT NOT NULL CHECK (tipo IN ('previsao_diaria','chuva_forte','geada')),
  mensagem    TEXT NOT NULL,
  dados_json  JSONB,
  data_ref    DATE NOT NULL,
  enviado_em  TIMESTAMPTZ NOT NULL,
  status      TEXT NOT NULL CHECK (status IN ('enviado','falhou')),
  erro        TEXT
);
CREATE INDEX IF NOT EXISTS ix_alertas_usuario ON alertas_enviados (usuario_id, enviado_em DESC);
CREATE INDEX IF NOT EXISTS ix_alertas_dedupe ON alertas_enviados (usuario_id, cidade_id, tipo, enviado_em);

CREATE TABLE IF NOT EXISTS previsoes_cache (
  chave       TEXT PRIMARY KEY,
  previsao    JSONB NOT NULL,
  salvo_em    TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS cidades_busca_cache (
  consulta    TEXT PRIMARY KEY,
  resultados  JSONB NOT NULL,
  buscado_em  TIMESTAMPTZ NOT NULL
);
`

function postgresDb(query: (sql: string, values?: unknown[]) => Promise<{ rows: QueryResultRow[]; rowCount: number | null }>, pool: Pool, client?: PoolClient): DB {
  return {
    async query<T extends QueryResultRow>(sql: string, values: unknown[] = []) {
      let index = 0
      const statement = sql.replace(/\?/g, () => `$${++index}`)
      const result = await query(statement, values)
      const lastResult = Array.isArray(result) ? result[result.length - 1] : result
      return {
        rows: (lastResult?.rows ?? []) as T[],
        rowCount: lastResult?.rowCount ?? lastResult?.rows?.length ?? 0,
      }
    },
    async transaction<T>(callback: (db: DB) => Promise<T>) {
      const connection = await pool.connect()
      try {
        await connection.query('BEGIN')
        const result = await callback(postgresDb(connection.query.bind(connection), pool, connection))
        await connection.query('COMMIT')
        return result
      } catch (error) {
        await connection.query('ROLLBACK')
        throw error
      } finally {
        connection.release()
      }
    },
    async close() {
      if (!client) await pool.end()
    },
  }
}

export async function openDb(connectionString: string): Promise<DB> {
  if (!connectionString) throw new Error('DATABASE_URL não foi definida')
  const pool = new Pool({ connectionString })
  const db = postgresDb(pool.query.bind(pool), pool)
  try {
    await pool.query(SCHEMA)
    await db.query('SELECT 1')
    return db
  } catch (error) {
    await pool.end()
    throw error
  }
}

